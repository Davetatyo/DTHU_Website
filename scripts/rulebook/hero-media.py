#!/usr/bin/env python3
"""Hero boards and leaflets for the Szabálytár, from https://dice-throne.fandom.com.

Run from the repository root when heroes are added (needs curl and Pillow):
    python3 scripts/rulebook/hero-media.py <work folder outside the repository>
It downloads each hero's images into the work folder (kept for the next run), writes the web
versions to public/szabalytar/img/heroes/boards/ and generates
src/features/rulebook/data/hero-media.ts. Edit the tables below, not the generated file.
"""
import json, os, re, subprocess, sys, time, urllib.parse
from PIL import Image

API = "https://dice-throne.fandom.com/api.php"
UA = "DTHU-site-image-lookup/1.0"
CONTENT = "src/features/rulebook/content/hero"
OUT = "public/szabalytar/img/heroes/boards"
DATA = "src/features/rulebook/data/hero-media.ts"

# The site's hero id -> wiki page, where the title can't be worked out from the id.
PAGES = {"spider-man": "Spider-Man"}
# Boards that aren't named "board" on the wiki.
EXTRA = {"necromancer": ["File:Necromancer.png"]}
# Left out: alternate art, and leaflet sides that are only a picture.
SKIP = {"File:Paladin board alternate art.png", "File:Cursed Pirate leaflet 2.png", "File:Pale Lady insert 2.png"}
# Heroes with two: what each one is called, in the order they appear.
NAMED = {
    "File:Jean Grey board 1.2.png": (0, "Jean Grey"),
    "File:Jean Grey board 2.2.png": (1, "Sötét Főnix"),
    "File:Cursed Pirate board 1.png": (0, "Emberi"),
    "File:Cursed Pirate board 2.png": (1, "Elátkozott"),
    "File:Pale Lady board 2.png": (0, "Sápadt Hölgy"),
    "File:Pale Lady board 1.png": (1, "Werewolf"),
    "File:Necromancer insert 1.png": (0, None),
    "File:Necromancer insert 2.png": (1, "Élőholt"),
}

FULL_MAX_WIDTH = 2000
THUMB_WIDTH = {"board": 760, "leaflet": 560}


def curl(url, *args):
    return subprocess.run(["curl", "-sS", "--fail", "-L", "-m", "120", "-A", UA, *args, url], capture_output=True, check=True).stdout


def query(**params):
    params.update(action="query", format="json")
    return json.loads(curl(API + "?" + urllib.parse.urlencode(params)))


def wiki_images(page, extra):
    pages = query(prop="images", imlimit="200", titles=page, redirects="1")["query"]["pages"]
    titles = [i["title"] for p in pages.values() for i in p.get("images", [])]
    wanted = [t for t in titles if re.search(r"board|insert|leaflet", t, re.I) and t not in SKIP] + extra
    if not wanted:
        return {}
    found = query(prop="imageinfo", iiprop="url", titles="|".join(wanted))["query"]["pages"]
    return {p["title"]: p["imageinfo"][0]["url"] for p in found.values() if p.get("imageinfo")}


def save(image, path, width, quality):
    if image.width > width:
        image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
    image.save(path, "WEBP", quality=quality, method=6)
    return image.size


def main(work):
    os.makedirs(work, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    data, missing = {}, []
    for name in sorted(os.listdir(CONTENT)):
        hero = name[:-5]
        page = PAGES.get(hero, " ".join(w.capitalize() for w in hero.split("-")))
        images = wiki_images(page, EXTRA.get(hero, []))
        items = []
        for title, url in images.items():
            kind = "leaflet" if re.search(r"insert|leaflet", title, re.I) else "board"
            order, label = NAMED.get(title, (0, None))
            items.append(dict(kind=kind, order=order, label=label, title=title, url=url))
        if not items:
            missing.append(hero)
            continue
        items.sort(key=lambda i: (i["kind"] != "board", i["order"]))
        count = {"board": 0, "leaflet": 0}
        entries = []
        for item in items:
            source = os.path.join(work, hero + "__" + re.sub(r"[^A-Za-z0-9.]+", "_", item["title"][5:]))
            if not os.path.exists(source):
                with open(source, "wb") as f:
                    f.write(curl(item["url"]))
                time.sleep(0.4)
            count[item["kind"]] += 1
            stem = f"{hero}-{item['kind']}" + (f"-{count[item['kind']]}" if count[item["kind"]] > 1 else "")
            image = Image.open(source).convert("RGBA")
            width, height = save(image, f"{OUT}/{stem}.webp", FULL_MAX_WIDTH, 80)
            save(image, f"{OUT}/{stem}-thumb.webp", THUMB_WIDTH[item["kind"]], 72)
            entries.append(dict(kind=item["kind"], label=item["label"], file=stem, width=width, height=height))
        data[hero] = entries
    lines = [
        "// Generated by scripts/rulebook/hero-media.py. Edit the script's tables, not this file.",
        'import type { HeroMediaItem } from "../lib/hero-media";',
        "",
        "export const HERO_MEDIA: Record<string, HeroMediaItem[]> = {",
    ]
    for hero, entries in data.items():
        lines.append(f"  {json.dumps(hero)}: {json.dumps(entries, ensure_ascii=False)},")
    lines.append("};")
    with open(DATA, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(data)} heroes, no images for: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main(sys.argv[1])
